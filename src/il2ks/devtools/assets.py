@dataclass(frozen=True)
class Asset:
    path: str  # relative to static/il2ks/img/
    used_in: str
    size: str
    priority: Priority
    release: bool  # must exist (and be wired) for the first release; a placeholder is enough
    dynamic: bool = False  # loaded by a computed name (insignia choice, aircraft slug), so no literal reference

    @property
    def group(self) -> str:
        return self.path.split("/", 1)[0]


# --- the manifest ------------------------------------------------------------------------------------------------


def _outcome_usage() -> dict[str, str]:
    """outcome/<name> -> the labels (display.py badge tables) that use it."""
    usage: dict[str, list[str]] = {}
    for table, where in (
        (display.OUTCOMES, "sortie outcome"),
        (display.FATES, "pilot fate"),
        (display.STATUSES, "pilot status"),
    ):
        for key, (_label, _tone, icon) in table.items():
            if not icon:
                continue
            usage.setdefault(f"{icon}.svg", []).append(f"{where} `{key}`")
    return {path: "; ".join(parts) for path, parts in usage.items()}


