# --- tabler sources (README.md is the record; the manifest does not repeat it) -----------------------------------


def tabler_sources(readme: Path = README) -> dict[str, str]:
    """`event/spawn.svg` -> `login`, from the README's Tabler table."""
    rows = re.findall(
        r"^\| `([a-z0-9/_-]+\.svg)` \| `([a-z0-9-]+)` \|$", readme.read_text(encoding="utf-8"), re.MULTILINE
    )
    return dict(rows)


def source_of(path: str, tabler: dict[str, str]) -> str:
    if path in tabler:
        return f"Tabler `{tabler[path]}`"
    if path.startswith("flag/"):
        return "flag-icons (MIT)"
    if path.startswith(OURS):
        return "own drawing"
    return "none yet"


# --- what the code references and what is on disk ----------------------------------------------------------------

_QUOTED = re.compile(
    r"""["']((?:aircraft|brand|coalition|event|ground|outcome|role|stat|flag|medal|pattern|illustration)/[a-z0-9][a-z0-9_/-]*)["']"""
)
_PATHED = re.compile(
    r"img/((?:aircraft|brand|coalition|event|ground|outcome|role|stat|flag|medal|pattern|illustration)/[a-z0-9][a-z0-9_/-]*\.(?:svg|png|webp))"
)


def referenced() -> dict[str, list[str]]:
    """Image paths (with extension) named literally in templates, CSS, JS and Python, with the files naming them.

    Names built at run time (insignia choice, an aircraft's own icon) are not found here: those manifest entries are
    marked `dynamic`."""
    files: Iterable[Path] = [
        *(WEB_DIR / "templates").rglob("*.html"),
        *WEB_DIR.rglob("*.py"),
        *(WEB_DIR / "static" / "il2ks").glob("*.css"),
        *(WEB_DIR / "static" / "il2ks").glob("*.js"),
    ]
    found: dict[str, list[str]] = {}
    for path in files:
        text = path.read_text(encoding="utf-8")
        names = [f"{m.group(1)}.svg" for m in _QUOTED.finditer(text)] + [m.group(1) for m in _PATHED.finditer(text)]
        for name in names:
            where = found.setdefault(name, [])
            if path.name not in where:
                where.append(path.name)
    return found


def on_disk() -> set[str]:
    return {p.relative_to(IMG_DIR).as_posix() for p in IMG_DIR.rglob("*") if p.is_file() and p.name != "README.md"}


def status_of(asset: Asset, disk: set[str], refs: dict[str, list[str]]) -> Status:
    used = asset.dynamic or asset.path in refs
    if asset.path in disk:
        return "shipped" if used else "unused"
    return "missing" if asset.path in refs else "planned"


@dataclass(frozen=True)
class Drift:
    """Differences between the manifest, the code and the disk. All lists empty = the brief is complete."""

    missing: list[str]  # referenced by code (or release-required and wired) but no file
    unlisted_files: list[str]  # on disk, not in the manifest
    unlisted_refs: list[str]  # named in code, not in the manifest
    unused: list[
        str
    ]  # release-required and on disk, but nothing references it (optional ones may sit unused: state `unused`)
    tabler_unknown: list[str]  # on disk, neither in the README's Tabler table nor an own drawing
    tabler_stale: list[str]  # in the README's Tabler table, no file

    def ok(self) -> bool:
        return not any(
            (self.missing, self.unlisted_files, self.unlisted_refs, self.unused, self.tabler_unknown, self.tabler_stale)
        )


def find_drift(manifest: list[Asset] | None = None) -> Drift:
    manifest = manifest or build_manifest()
    disk, refs, tabler = on_disk(), referenced(), tabler_sources()
    listed = {a.path for a in manifest}
    dynamic = {a.path for a in manifest if a.dynamic}
    return Drift(
        missing=sorted(p for p in refs if p not in disk and p not in dynamic)
        + sorted(a.path for a in manifest if a.release and a.path not in disk),
        unlisted_files=sorted(disk - listed),
        unlisted_refs=sorted(set(refs) - listed),
        unused=sorted(
            a.path for a in manifest if a.release and a.path in disk and not a.dynamic and a.path not in refs
        ),
        tabler_unknown=sorted(p for p in disk if p not in tabler and not p.startswith(OURS)),
        tabler_stale=sorted(p for p in tabler if p not in disk),
    )


# --- the brief -----------------------------------------------------------------------------------------------------


def render(manifest: list[Asset] | None = None) -> str:
    """The generated section of doc 15 (between START and END)."""
    manifest = manifest or build_manifest()
    disk, refs, tabler = on_disk(), referenced(), tabler_sources()
    shipped = sum(a.path in disk for a in manifest)
    lines = [
        START,
        "",
        "## Complete file inventory",
        "",
        "Generated from the code by `uv run il2ks dev assets --write`; a unit test fails when it drifts from the "
        "templates, "
        "the Python icon maps, the CSS or the files in `static/il2ks/img/`. Paths are relative to "
        "`src/il2ks/web/static/il2ks/img/`. **Release**: *yes* = the page needs the file (a placeholder is enough), "
        "*no* = optional or later. **State**: *shipped* = a placeholder file exists, *unused* = shipped but no page "
        "uses it yet, *planned* = not drawn and not "
        "(fully) wired yet; the site works without it. The uploaded server logo is not a static file: it is "
        "re-encoded to PNG (at most 256 px high) and served from `/media/branding/`.",
        "",
        f"Total: {len(manifest)} files in {len(GROUPS)} groups; {shipped} shipped as placeholders "
        f"({sum(status_of(a, disk, refs) == 'unused' for a in manifest)} of them not used by any page yet), "
        f"{len(manifest) - shipped} planned.",
        "",
    ]
    for group in GROUPS:
        rows = [a for a in manifest if a.group == group]
        count = sum(a.path in disk for a in rows)
        lines += [
            f"### {GROUP_TITLES[group]}: {len(rows)} files ({count} shipped)",
            "",
            "| File | Used in | Size / format | Placeholder source | Release | Prio | State |",
            "|---|---|---|---|---|---|---|",
        ]
        for a in rows:
            state = status_of(a, disk, refs)
            lines.append(
                f"| `{a.path}` | {a.used_in} | {a.size} | {source_of(a.path, tabler)} | "
                f"{'yes' if a.release else 'no'} | {a.priority} | {state} |"
            )
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def brief_path(root: Path | None = None) -> Path:
    base = root or Path(__file__).resolve().parents[3]
    return base / "design_doc" / BRIEF_NAME


def brief_section(text: str) -> str | None:
    start, end = text.find(START), text.find(END)
    return text[start : end + len(END)] if start != -1 and end > start else None


def write_brief(path: Path) -> bool:
    """Replace the generated section of the brief (appended if absent). True when the file changed."""
    text = path.read_text(encoding="utf-8")
    section = render()
    current = brief_section(text)
    new = text.replace(current, section) if current else text.rstrip("\n") + "\n\n" + section + "\n"
    if new == text:
        return False
    path.write_text(new, encoding="utf-8", newline="\n")
    return True


def summary(manifest: list[Asset] | None = None) -> str:
    manifest = manifest or build_manifest()
    disk = on_disk()
    out = ["group          files  shipped  planned  release-required"]
    for group in GROUPS:
        rows = [a for a in manifest if a.group == group]
        have = sum(a.path in disk for a in rows)
        out.append(f"{group:<14}{len(rows):>6}{have:>9}{len(rows) - have:>9}{sum(a.release for a in rows):>18}")
    out.append(f"{'total':<14}{len(manifest):>6}{len(disk):>9}{len(manifest) - len(disk):>9}")
    drift = find_drift(manifest)
    for label, items in (
        ("referenced or release-required but missing", drift.missing),
        ("on disk but not in the manifest", drift.unlisted_files),
        ("referenced but not in the manifest", drift.unlisted_refs),
        ("shipped but referenced nowhere", drift.unused),
        ("on disk, not in the README (Tabler table or own drawings)", drift.tabler_unknown),
        ("in the README's Tabler table but no file", drift.tabler_stale),
    ):
        if items:
            out.append(f"{label}: {', '.join(items)}")
    return "\n".join(out)


def run(*, check: bool, write: bool) -> int:
    """`il2ks dev assets`: print the summary; `--check` exits 1 on drift; `--write` rewrites the brief's inventory."""
    path = brief_path()
    if write and write_brief(path):
        print(f"rewrote the inventory in {path}")
    print(summary())
    if not check:
        return 0
    drift = find_drift()
    in_brief = brief_section(path.read_text(encoding="utf-8")) == render()
    if not in_brief:
        print("design_doc/15_visual_assets.md is out of date: run `uv run il2ks dev assets --write`", flush=True)
    return 0 if drift.ok() and in_brief else 1
